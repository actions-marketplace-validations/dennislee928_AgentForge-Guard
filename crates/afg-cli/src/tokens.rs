//! Out-of-band approval tokens (T7.4).
//!
//! 1. When a `require-approval` decision can't be approved at a terminal,
//!    `afg run` writes `<audit dir>/../approvals/pending/<id>.json` and exits
//!    126.
//! 2. A human runs `afg approve <id>` in their own terminal. It writes
//!    `approvals/tokens/<id>.json`, which holds an HMAC-SHA256 over the
//!    decision digest, keyed by `~/.config/agentforge/approval.key`.
//! 3. Re-running the *same* command (the same argv, cwd, backend, rule and
//!    policy hash) finds the token, verifies it and deletes it before
//!    executing. Tokens are single-use and expire after 15 minutes.
//!
//! What keeps an agent from approving itself: `afg` can never be run through
//! `afg` (a built-in forbidden rule), and the key's directory is a built-in
//! protected path. An agent that is not confined to afg is out of scope
//! (docs/security-boundaries.md).

use std::path::{Path, PathBuf};

use afg_core::Decision;
use anyhow::{Context, bail};
use hmac::{KeyInit, Mac};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

type HmacSha256 = hmac::Hmac<Sha256>;

/// How long a token stays valid.
pub const TOKEN_TTL_SECS: u64 = 15 * 60;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Pending {
    pub id: String,
    pub digest: String,
    pub argv: Vec<String>,
    pub cwd: String,
    pub backend: String,
    pub rule_id: String,
    pub policy_hash: String,
    pub created_unix: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Token {
    pub id: String,
    pub digest: String,
    pub expires_unix: u64,
    pub mac: String,
}

pub fn now_unix() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// Binds an approval to exactly this decision.
pub fn decision_digest(d: &Decision, cwd: &Path) -> String {
    let canon = serde_json::json!({
        "argv": d.normalized.original,
        "cwd": cwd.display().to_string(),
        "backend": d.backend,
        "rule": d.rule_id,
        "policy": d.policy_hash,
        "program": d.normalized.program,
    });
    let h = Sha256::digest(canon.to_string().as_bytes());
    h.iter().map(|b| format!("{b:02x}")).collect()
}

pub fn approvals_dir(root: &Path, audit_dir: &str) -> PathBuf {
    let audit = root.join(audit_dir);
    audit
        .parent()
        .map(|p| p.join("approvals"))
        .unwrap_or_else(|| root.join(".agentforge/approvals"))
}

fn key_path(home: &Path) -> PathBuf {
    home.join(".config/agentforge/approval.key")
}

fn read_key(home: &Path) -> anyhow::Result<Vec<u8>> {
    let k = std::fs::read(key_path(home))
        .context("no approval key; run `afg approve` once to create it")?;
    anyhow::ensure!(k.len() >= 32, "approval key is too short");
    Ok(k)
}

/// Create the key (mode 0600) if it does not exist yet.
pub fn ensure_key(home: &Path) -> anyhow::Result<Vec<u8>> {
    let p = key_path(home);
    if p.exists() {
        return read_key(home);
    }
    let dir = p.parent().expect("has parent");
    std::fs::create_dir_all(dir)?;
    let mut key = vec![0u8; 32];
    getrandom::fill(&mut key).map_err(|e| anyhow::anyhow!("random key: {e}"))?;
    let mut opts = std::fs::OpenOptions::new();
    opts.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
        opts.mode(0o600);
        std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))?;
    }
    use std::io::Write;
    opts.open(&p)?.write_all(&key)?;
    Ok(key)
}

fn mac_hex(key: &[u8], id: &str, digest: &str, expires: u64) -> String {
    let mut m = <HmacSha256 as KeyInit>::new_from_slice(key).expect("any key length");
    m.update(format!("afg-approval-v1\n{id}\n{digest}\n{expires}").as_bytes());
    m.finalize()
        .into_bytes()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

fn write_json(path: &Path, v: &impl Serialize) -> anyhow::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, serde_json::to_vec_pretty(v)?)?;
    Ok(())
}

pub fn write_pending(dir: &Path, p: &Pending) -> anyhow::Result<()> {
    write_json(&dir.join("pending").join(format!("{}.json", p.id)), p)
}

pub fn list_pending(dir: &Path) -> Vec<Pending> {
    let mut out: Vec<Pending> = std::fs::read_dir(dir.join("pending"))
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter_map(|e| std::fs::read(e.path()).ok())
        .filter_map(|b| serde_json::from_slice(&b).ok())
        .collect();
    out.sort_by_key(|p| p.created_unix);
    out
}

/// Ids are generated by afg (`new_id`). Anything else is rejected so a
/// crafted id cannot escape the approvals directory.
fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 64 && id.chars().all(|c| c.is_ascii_hexdigit() || c == '-')
}

/// Approve a pending request: write a signed token and remove the request.
pub fn approve(dir: &Path, home: &Path, id: &str) -> anyhow::Result<Token> {
    if !valid_id(id) {
        bail!("invalid approval id `{id}`");
    }
    let pending_path = dir.join("pending").join(format!("{id}.json"));
    let p: Pending = serde_json::from_slice(
        &std::fs::read(&pending_path).with_context(|| format!("no pending approval `{id}`"))?,
    )?;
    let key = ensure_key(home)?;
    let expires = now_unix() + TOKEN_TTL_SECS;
    let t = Token {
        id: p.id.clone(),
        digest: p.digest.clone(),
        expires_unix: expires,
        mac: mac_hex(&key, &p.id, &p.digest, expires),
    };
    write_json(&dir.join("tokens").join(format!("{id}.json")), &t)?;
    std::fs::remove_file(&pending_path)?;
    Ok(t)
}

/// Find, verify and consume a token for `digest`. Returns the token id. A
/// token is valid only if it is unexpired, its MAC verifies, and it could be
/// deleted, which makes it single-use.
pub fn consume(dir: &Path, home: Option<&Path>, digest: &str) -> Option<String> {
    let home = home?;
    let key = read_key(home).ok()?;
    let entries = std::fs::read_dir(dir.join("tokens")).ok()?;
    for e in entries.filter_map(Result::ok) {
        let path = e.path();
        let Ok(bytes) = std::fs::read(&path) else {
            continue;
        };
        let Ok(t) = serde_json::from_slice::<Token>(&bytes) else {
            continue;
        };
        if t.expires_unix < now_unix() {
            let _ = std::fs::remove_file(&path);
            continue;
        }
        if t.digest != digest {
            continue;
        }
        let mut m = <HmacSha256 as KeyInit>::new_from_slice(&key).expect("any key length");
        m.update(
            format!(
                "afg-approval-v1\n{}\n{}\n{}",
                t.id, t.digest, t.expires_unix
            )
            .as_bytes(),
        );
        let Ok(tag) = (0..t.mac.len())
            .step_by(2)
            .map(|i| {
                t.mac
                    .get(i..i + 2)
                    .and_then(|h| u8::from_str_radix(h, 16).ok())
            })
            .collect::<Option<Vec<u8>>>()
            .ok_or(())
        else {
            continue;
        };
        if m.verify_slice(&tag).is_err() {
            continue;
        }
        if std::fs::remove_file(&path).is_ok() {
            return Some(t.id);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp() -> tempfile::TempDir {
        tempfile::tempdir().unwrap()
    }

    fn pending(id: &str, digest: &str) -> Pending {
        Pending {
            id: id.into(),
            digest: digest.into(),
            argv: vec!["kubectl".into(), "apply".into()],
            cwd: "/w".into(),
            backend: "local".into(),
            rule_id: "infra".into(),
            policy_hash: "sha256:x".into(),
            created_unix: now_unix(),
        }
    }

    #[test]
    fn approve_then_consume_once() {
        let (d, h) = (tmp(), tmp());
        write_pending(d.path(), &pending("01ab-cd", "dig")).unwrap();
        assert_eq!(list_pending(d.path()).len(), 1);
        approve(d.path(), h.path(), "01ab-cd").unwrap();
        assert!(list_pending(d.path()).is_empty());
        assert_eq!(
            consume(d.path(), Some(h.path()), "other"),
            None,
            "bound to the digest"
        );
        assert_eq!(
            consume(d.path(), Some(h.path()), "dig").as_deref(),
            Some("01ab-cd")
        );
        assert_eq!(consume(d.path(), Some(h.path()), "dig"), None, "single use");
    }

    #[test]
    fn forged_or_expired_tokens_rejected() {
        let (d, h) = (tmp(), tmp());
        ensure_key(h.path()).unwrap();
        let forged = Token {
            id: "1".into(),
            digest: "dig".into(),
            expires_unix: now_unix() + 60,
            mac: "00".repeat(32),
        };
        write_json(&d.path().join("tokens/1.json"), &forged).unwrap();
        assert_eq!(consume(d.path(), Some(h.path()), "dig"), None);

        write_pending(d.path(), &pending("2", "dig")).unwrap();
        let mut t = approve(d.path(), h.path(), "2").unwrap();
        t.expires_unix = now_unix() - 1;
        write_json(&d.path().join("tokens/2.json"), &t).unwrap();
        assert_eq!(
            consume(d.path(), Some(h.path()), "dig"),
            None,
            "expired (and MAC no longer matches)"
        );
    }

    #[test]
    fn ids_cannot_traverse() {
        let (d, h) = (tmp(), tmp());
        assert!(approve(d.path(), h.path(), "../../etc/passwd").is_err());
        assert!(approve(d.path(), h.path(), "").is_err());
    }

    #[cfg(unix)]
    #[test]
    fn key_is_private() {
        use std::os::unix::fs::PermissionsExt;
        let h = tmp();
        ensure_key(h.path()).unwrap();
        let mode = std::fs::metadata(key_path(h.path()))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600);
        assert_eq!(ensure_key(h.path()).unwrap(), ensure_key(h.path()).unwrap());
    }
}
